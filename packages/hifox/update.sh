#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PKGBUILD_PATH="${SCRIPT_DIR}/PKGBUILD"
SRCINFO_PATH="${SCRIPT_DIR}/.SRCINFO"
BASE_URL="https://file-assets.hifox.com/download"

require_command() {
  if ! command -v "$1" >/dev/null 2>&1; then
    printf 'missing dependency: %s\n' "$1" >&2
    exit 1
  fi
}

require_command awk
require_command curl
require_command jq
require_command makepkg
require_command sha256sum

current_pkgver=""
current_pkgrel=""
current_sha256_x64=""
current_sha256_arm64=""
if [[ -f "${PKGBUILD_PATH}" ]]; then
  current_pkgver="$(awk -F= '/^pkgver=/ {print $2; exit}' "${PKGBUILD_PATH}")"
  current_pkgrel="$(awk -F= '/^pkgrel=/ {print $2; exit}' "${PKGBUILD_PATH}")"
  current_sha256_x64="$(awk -F"'" '/^sha256sums_x86_64=/ {print $2; exit}' "${PKGBUILD_PATH}")"
  current_sha256_arm64="$(awk -F"'" '/^sha256sums_aarch64=/ {print $2; exit}' "${PKGBUILD_PATH}")"
fi

metadata_x64="$(curl -fsSL --retry 5 --retry-all-errors "${BASE_URL}/latest/linux/amd64.json")"
metadata_arm64="$(curl -fsSL --retry 5 --retry-all-errors "${BASE_URL}/latest/linux/arm64.json")"

pkgver="$(printf '%s\n' "${metadata_x64}" | jq -r '.version')"
artifact_x64="$(printf '%s\n' "${metadata_x64}" | jq -r '.artifact')"
artifact_arm64="$(printf '%s\n' "${metadata_arm64}" | jq -r '.artifact')"

if [[ -z "${pkgver}" || "${pkgver}" == "null" ]] \
  || ! [[ "${pkgver}" =~ ^[0-9A-Za-z][0-9A-Za-z._+-]*$ ]]; then
  printf 'failed to resolve latest HiFox CLI version\n' >&2
  exit 1
fi

if [[ "${artifact_x64}" != "HiFox-cli_linux_amd64.tar.gz" ]] \
  || [[ "${artifact_arm64}" != "HiFox-cli_linux_arm64.tar.gz" ]]; then
  printf 'unexpected upstream artifact names: %s, %s\n' "${artifact_x64}" "${artifact_arm64}" >&2
  exit 1
fi

tmpdir="$(mktemp -d)"
trap 'rm -rf "${tmpdir}"' EXIT

curl -fL --retry 5 --retry-all-errors "${BASE_URL}/${pkgver}/linux/${artifact_x64}" -o "${tmpdir}/${artifact_x64}" >/dev/null 2>&1
curl -fL --retry 5 --retry-all-errors "${BASE_URL}/${pkgver}/linux/${artifact_arm64}" -o "${tmpdir}/${artifact_arm64}" >/dev/null 2>&1

sha256_x64="$(sha256sum "${tmpdir}/${artifact_x64}" | awk '{print $1}')"
sha256_arm64="$(sha256sum "${tmpdir}/${artifact_arm64}" | awk '{print $1}')"

trap - EXIT
rm -rf "${tmpdir}"

if [[ "${current_pkgver}" == "${pkgver}" &&
      "${current_pkgrel}" =~ ^[0-9]+$ &&
      "${current_sha256_x64}" == "${sha256_x64}" &&
      "${current_sha256_arm64}" == "${sha256_arm64}" ]]; then
  pkgrel="${current_pkgrel}"
else
  if [[ "${current_pkgver}" == "${pkgver}" && "${current_pkgrel}" =~ ^[0-9]+$ ]]; then
    pkgrel="$((current_pkgrel + 1))"
  else
    pkgrel=1
  fi
fi

cat > "${PKGBUILD_PATH}" <<EOF
# Maintainer: duanluan <duanluan@outlook.com>

pkgname=hifox
pkgver=${pkgver}
pkgrel=${pkgrel}
pkgdesc='HiFox CLI: terminal client for the HiFox human and AI agent collaboration platform'
arch=('x86_64' 'aarch64')
url='https://hifox.com/'
license=('LicenseRef-Proprietary')
provides=("hifox-cli-bin=\${pkgver}")
conflicts=('hifox-cli-bin')
options=('!strip')
_base_url="https://file-assets.hifox.com/download"
source_x86_64=("hifox-cli_linux_amd64-\${pkgver}.tar.gz::\${_base_url}/\${pkgver}/linux/HiFox-cli_linux_amd64.tar.gz")
source_aarch64=("hifox-cli_linux_arm64-\${pkgver}.tar.gz::\${_base_url}/\${pkgver}/linux/HiFox-cli_linux_arm64.tar.gz")
sha256sums_x86_64=('${sha256_x64}')
sha256sums_aarch64=('${sha256_arm64}')

package() {
  install -Dm755 "\${srcdir}/hifox" "\${pkgdir}/usr/bin/hifox"

  # Completions are generated by running the prebuilt binary; skip them when
  # it cannot execute on the build host (for example a cross-architecture build).
  if "\${srcdir}/hifox" version >/dev/null 2>&1; then
    install -Dm644 <("\${srcdir}/hifox" completion bash) \\
      "\${pkgdir}/usr/share/bash-completion/completions/hifox"
    install -Dm644 <("\${srcdir}/hifox" completion zsh) \\
      "\${pkgdir}/usr/share/zsh/site-functions/_hifox"
    install -Dm644 <("\${srcdir}/hifox" completion fish) \\
      "\${pkgdir}/usr/share/fish/vendor_completions.d/hifox.fish"
  else
    printf 'skipping shell completions: the prebuilt binary does not run on this host\n' >&2
  fi
}
EOF

cd "${SCRIPT_DIR}"
makepkg --printsrcinfo > "${SRCINFO_PATH}"

printf '%s\n' "${pkgver}"
